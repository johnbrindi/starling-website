"""Generates starling-profiles.rsc: hotspot user profiles (packages) with an on-login script that
removes the user when its paid time ends (time starts at the FIRST login, like printed tickets).
Run:  python3 network/mikrotik/standalone/build_profiles.py
Edit PACKAGES / RATE below, re-run, then import the .rsc on the router."""
from pathlib import Path

RATE = "2M/5M"  # upload/download per customer (router view: rx/tx)
PACKAGES = [  # (profile name, RouterOS interval, price note, devices)
    ("1hour", "1h", "100 FCFA", 1),
    ("12hours", "12h", "150 FCFA", 1),
    ("24hours", "1d", "200 FCFA", 1),
    ("1week", "7d", "1350 FCFA", 1),
    ("2weeks", "14d", "2500 FCFA", 1),
    ("1month", "30d", "4500 FCFA", 2),
]

ON_LOGIN = r''':local u $user
:local n ("exp-" . $u)
:if ([:len [/system scheduler find where name=$n]] = 0) do={
/system scheduler add name=$n interval=DURATION policy=read,write,test comment="Starling: ends this hotspot user's time" on-event=(":do {/ip hotspot active remove [find where user=\"" . $u . "\"]} on-error={}; :do {/ip hotspot cookie remove [find where user=\"" . $u . "\"]} on-error={}; :do {/ip hotspot user remove [find where name=\"" . $u . "\"]} on-error={}; /system scheduler remove [find where name=\"" . $n . "\"]")
:delay 1s
:local c ""
:do {:set c [/ip hotspot user get [find where name=$u] comment]} on-error={}
:if ([:len $c] > 0) do={:set c ($c . " | ")}
:do {/ip hotspot user set [find where name=$u] comment=($c . "Started " . [/system clock get date] . " " . [/system clock get time] . " | ends " . [/system scheduler get [find where name=$n] next-run])} on-error={}
}'''


def ros_quote(s: str) -> str:
    """Quote a string for a RouterOS command line."""
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"').replace("$", "\\$").replace("\n", "\\r\\n") + '"'


# Free access for the family members who contributed to the Starlink: never expires, faster, 2 devices.
FAMILY = ("family", "5M/10M", 2)


def upsert(name: str, attrs: str) -> list[str]:
    """Create the profile if missing, then update it. Safe to re-import while users use the profile."""
    return [
        f':if ([:len [/ip hotspot user profile find where name="{name}"]] = 0) do={{ /ip hotspot user profile add name="{name}" }}',
        f'/ip hotspot user profile set [find where name="{name}"] {attrs}',
    ]


def main():
    out = [
        "# Juthelink - hotspot packages (user profiles) with automatic expiry.",
        "# Generated by build_profiles.py. Import on the router:  /import file-name=starling-profiles.rsc",
        "# Time starts at the customer's FIRST login and ends DURATION later (wall clock), even if they log off.",
        "# Safe to import again, even with customers online: existing profiles are updated in place.",
        "",
    ]
    for name, interval, price, devices in PACKAGES:
        script = ON_LOGIN.replace("DURATION", interval)
        out += upsert(
            name,
            f"shared-users={devices} rate-limit={RATE} idle-timeout=none "
            f"keepalive-timeout=3h status-autorefresh=1m add-mac-cookie=yes mac-cookie-timeout=3d "
            f"on-login={ros_quote(script)}",
        )
        out.append(f':put "Profile {name} ({interval}, {price}, {devices} device(s)) ready"')
    fname, frate, fdev = FAMILY
    out += upsert(
        fname,
        f"shared-users={fdev} rate-limit={frate} idle-timeout=none keepalive-timeout=3h "
        f'status-autorefresh=1m add-mac-cookie=yes mac-cookie-timeout=30d on-login=""',
    )
    out.append(f':put "Profile {fname} (free, never expires, {fdev} device(s), {frate}) ready"')
    out.append("")
    path = Path(__file__).with_name("starling-profiles.rsc")
    path.write_text("\n".join(out), encoding="ascii")
    Path(__file__).with_name("on-login-script.txt").write_text(
        "Paste into IP > Hotspot > User Profiles > (profile) > Scripts > On Login.\n"
        "Replace DURATION with the pass length: 1h, 12h, 1d, 7d, 14d, 30d.\n\n" + ON_LOGIN + "\n",
        encoding="ascii",
    )
    print(f"wrote {path}")


if __name__ == "__main__":
    main()
